"""Benchmark System 2 latency: PyTorch vs FP8 TensorRT, same navigation input,
engine load time excluded. Both paths produce identical output.
"""
import os
import sys
import json
import time
import subprocess
_R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _R)
sys.path.insert(0, os.path.join(_R, "lib"))
import torch  # noqa: E402
from engine_runner import ENGINE, REPKG  # noqa: E402

TRT = os.environ.get("TRT_EDGE_LLM", os.path.expanduser("~/TensorRT-Edge-LLM"))
ENG_LLM = os.path.dirname(ENGINE)
ENG_VIS = os.path.join(os.environ.get("WORK_DIR", os.path.expanduser("~/vln-opt-work")), "engines/system2_visual")
# NOTE: nothing in this recipe (or the source project) generates this manifest. It is a
# user-supplied list of golden samples. The preflight below says so rather than letting
# the benchmark die on a missing file.
# prompt_builder is the single source of truth for the VLN prompt and lives in the
# quantize path, so calibration and verification cannot drift apart. Walk up to the
# recipe root instead of counting parent levels -- these scripts sit at two depths.
_d = os.path.dirname(os.path.abspath(__file__))
while _d != "/" and not os.path.isdir(os.path.join(_d, "quantize")):
    _d = os.path.dirname(_d)
sys.path.insert(0, os.path.join(_d, "quantize"))

MANIFEST = os.path.join(os.environ.get("WORK_DIR", os.path.expanduser("~/vln-opt-work")), "golden/manifest_v3.json")
SCRATCH = os.path.expanduser(os.environ.get('VLN_OPT_OUT', '~/vln-opt-work/out'))
IMG_DIR = os.path.join(SCRATCH, "bench_imgs")
os.makedirs(IMG_DIR, exist_ok=True)
MINP, MAXP = 3136, 12845056
MAXNEW = 16


def fill_paths(conv, image_paths):
    out, j = [], 0
    for turn in conv:
        content = []
        for it in turn["content"]:
            if it["type"] == "image":
                content.append({"type": "image", "image": os.path.abspath(image_paths[j])})
                j += 1
            else:
                content.append({"type": "text", "text": it["text"]})
        out.append({"role": turn["role"], "content": content})
    return out


def run_llm_inference(requests):
    inp = os.path.join(SCRATCH, "bench_in.json")
    out = os.path.join(SCRATCH, "bench_out.json")
    json.dump({"batch_size": 1, "temperature": 0.0, "top_p": 1.0, "top_k": 1, "max_generate_length": MAXNEW,
               "requests": requests}, open(inp, "w"))
    env = dict(os.environ, EDGELLM_PLUGIN_PATH=f"{TRT}/build/libNvInfer_edgellm_plugin.so")
    t0 = time.perf_counter()
    r = subprocess.run([f"{TRT}/build/examples/llm/llm_inference", "--engineDir", ENG_LLM,
                        "--multimodalEngineDir", ENG_VIS, "--inputFile", inp, "--outputFile", out],
                       cwd=TRT, env=env, capture_output=True, text=True)
    dt = time.perf_counter() - t0
    resp = json.load(open(out)).get("responses", []) if os.path.exists(out) else []
    return dt, [x.get("output_text", "").strip() for x in resp], r.returncode


def _require_manifest():
    """Fail with an explanation instead of a bare FileNotFoundError.

    The golden manifest is a user-supplied list of samples; no script here produces one.
    """
    if not os.path.isfile(MANIFEST):
        raise SystemExit(
            f"[ERROR] golden manifest not found: {MANIFEST}\n"
            f"        MANIFEST is required and is not generated by this recipe. It should\n"
            f"        be a JSON file with a 'samples' list, each entry carrying episode,\n"
            f"        episode_idx, instruction and images -- the same shape\n"
            f"        quantize/benchmark_accuracy.py builds from LeRobot episodes.\n"
            f"        Override the location with WORK_DIR or create the file.")


def main():
    _require_manifest()
    dev = "cuda"
    from transformers import AutoProcessor, Qwen2_5_VLForConditionalGeneration
    from prompt_builder import build_sample_inputs, build_conversation, build_conversation_lookdown
    man = json.load(open(MANIFEST))
    t2 = next(s for s in man["samples"] if s.get("turn") == 2)
    t1 = next(s for s in man["samples"] if s.get("turn", 1) == 1)
    cases = [("turn2/coord", t2), ("turn1/action", t1)]

    print("[1/3] Load model + processor (PyTorch repo path)")
    model = Qwen2_5_VLForConditionalGeneration.from_pretrained(
        REPKG, torch_dtype=torch.bfloat16, attn_implementation="flash_attention_2",
        low_cpu_mem_usage=True).to(dev).eval()
    proc = AutoProcessor.from_pretrained(REPKG, trust_remote_code=True, min_pixels=MINP, max_pixels=MAXP)

    results = {}
    reqs = {}
    print("[2/3] PyTorch generate (2 warm-up, 5 timed runs)")
    for name, s in cases:
        inp = build_sample_inputs(s, proc).to(dev)
        S = inp["input_ids"].shape[1]
        for _ in range(2):  # warm
            with torch.no_grad():
                model.generate(**inp, max_new_tokens=MAXNEW, do_sample=False, use_cache=True)
        torch.cuda.synchronize()
        ts = []
        for _ in range(5):
            torch.cuda.synchronize()
            t0 = time.perf_counter()
            with torch.no_grad():
                out = model.generate(**inp, max_new_tokens=MAXNEW, do_sample=False, use_cache=True)
            torch.cuda.synchronize()
            ts.append(time.perf_counter() - t0)
        ntok = out.shape[1] - S
        txt = proc.tokenizer.decode(out[0, S:], skip_special_tokens=True).strip()
        results[name] = {"S": S, "ntok": int(ntok), "torch_s": sum(ts) / len(ts), "torch_out": txt}
        print(f"    {name}: S={S} gen={ntok}tok torch={results[name]['torch_s']*1000:.0f}ms out={txt!r}")
        # build llm_inference request (same sample)
        turn = s.get("turn", 1)
        conv = (build_conversation_lookdown(s["episode_idx"], s["instruction"], s["assistant_turn1"])
                if turn == 2 else build_conversation(s["episode_idx"], s["instruction"])[0])
        conv = conv if isinstance(conv, list) else [conv]
        reqs[name] = {"messages": fill_paths(conv, s["images"])}
    del model
    torch.cuda.empty_cache()

    print("[3/3] FP8 TensorRT llm_inference (load excluded: t_1 vs t_N)")
    N = 11
    for name, _ in cases:
        t1s, o1, rc1 = run_llm_inference([reqs[name]])
        tNs, oN, rcN = run_llm_inference([reqs[name]] * N)
        per = (tNs - t1s) / (N - 1)
        results[name]["fp8_s"] = per
        results[name]["fp8_out"] = (oN[0] if oN else "<none>")
        results[name]["load_s"] = t1s - per
        print(
            f"    {name}: t_1={t1s:.2f}s t_{N}={tNs:.2f}s → per-req={per*1000:.0f}ms (load≈{results[name]['load_s']:.1f}s) out={results[name]['fp8_out']!r}")  # noqa: E501

    print("\n" + "=" * 70)
    print(f"{'case':<14}{'S':>6}{'gen':>5}{'PyTorch':>12}{'FP8 TRT':>12}{'speedup':>10}")
    print("-" * 70)
    for name, _ in cases:
        r = results[name]
        sp = r["torch_s"] / r["fp8_s"]
        print(f"{name:<14}{r['S']:>6}{r['ntok']:>5}{r['torch_s']*1000:>10.0f}ms{r['fp8_s']*1000:>10.0f}ms{sp:>9.2f}x")
    report_dir = os.path.join(os.environ.get("WORK_DIR",
                                             os.path.expanduser("~/vln-opt-work")), "reports")
    os.makedirs(report_dir, exist_ok=True)   # the final line used to crash without this
    json.dump(results, open(os.path.join(report_dir, "bench_e2e.json"), "w"),
              indent=2, ensure_ascii=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
